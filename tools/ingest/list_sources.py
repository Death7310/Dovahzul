#!/usr/bin/env python3
"""Rewrite the page table in research/sources/uesp/ATTRIBUTION.md from manifest.d.

Standard library only; reads the provenance records, fetches nothing.

    python3 tools/ingest/list_sources.py           # rewrite the table in place
    python3 tools/ingest/list_sources.py --print   # print the table, change nothing

Only the text between the two marker lines in ATTRIBUTION.md is replaced; the
rest of that file is written by hand.  Each row links the article, the exact
revision that was saved, and the article's history page (the wiki's reuse terms
ask for a link to the article and to its history).
"""
import json
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "research" / "sources" / "uesp"
TARGET = SRC / "ATTRIBUTION.md"
BEGIN = "<!-- BEGIN PAGE TABLE (generated by tools/ingest/list_sources.py) -->"
END = "<!-- END PAGE TABLE -->"


def table():
    records = [json.loads(p.read_text(encoding="utf-8"))
               for p in sorted((SRC / "manifest.d").glob("*.json"))]
    records.sort(key=lambda r: r["title"])
    lines = ["%d pages. Revision dates run from %s to %s; all were fetched on %s." % (
        len(records), min(r["timestamp"] for r in records)[:10],
        max(r["timestamp"] for r in records)[:10],
        " and ".join(sorted({r["fetched_at"][:10] for r in records}))), "",
        "| Article | Revision saved | Revision date (UTC) | History |",
        "|---|---|---|---|"]
    for r in records:
        title = r["title"]
        quoted = urllib.parse.quote(title.replace(" ", "_"), safe=":/()',!-._~")
        article = "https://en.uesp.net/wiki/" + quoted
        history = "https://en.uesp.net/w/index.php?title=%s&action=history" % \
            urllib.parse.quote(title.replace(" ", "_"), safe="")
        permalink = "https://en.uesp.net/w/index.php?oldid=%d" % r["revid"]
        shown = title.replace("|", "\\|")
        lines.append("| [%s](<%s>) | [%d](%s) | %s | [history](%s) |" % (
            shown, article, r["revid"], permalink, r["timestamp"], history))
    return "\n".join(lines)


def main():
    text = table()
    if "--print" in sys.argv[1:]:
        print(text)
        return 0
    doc = TARGET.read_text(encoding="utf-8")
    if BEGIN not in doc or END not in doc:
        sys.stderr.write("marker lines not found in %s\n" % TARGET)
        return 1
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    TARGET.write_text(head + BEGIN + "\n" + text + "\n" + END + tail, encoding="utf-8")
    print("rewrote the page table in %s" % TARGET.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
